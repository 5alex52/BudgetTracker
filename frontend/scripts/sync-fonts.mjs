/**
 * sync-fonts.mjs — self-hosting the medeo-font fonts.
 *
 * Takes the CSS from the medeo-font package and writes it to src/styles/fonts.generated.css,
 * rewriting url() to stable /fonts/medeo/... paths (needed for <link rel="preload">).
 * The woff2 files themselves are copied into public/fonts/medeo/.
 *
 * Run: node scripts/sync-fonts.mjs   (or automatically via npm run fonts)
 * No CDN: files are served from our own origin.
 */
import { readFile, writeFile, mkdir, copyFile, readdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const pkgDist = resolve(root, 'node_modules/medeo-font/dist')
const outCssDir = resolve(root, 'src/styles')
const outFontsDir = resolve(root, 'public/fonts/medeo')

const STYLES = ['sans', 'mono'] // serif and pixel are not used

/** Drops @font-face with font-style: italic — the UI has no italic styles. */
function dropItalic(css) {
  return css.replace(/@font-face\s*{[^}]*font-style:\s*italic[^}]*}/g, '')
}

/** url("./fonts/medeo-sans/X.woff2") → url("/fonts/medeo/medeo-sans/X.woff2") */
function rewriteUrls(css) {
  return css.replace(/url\(["']?\.\/fonts\/([^"')]+)["']?\)/g, 'url("/fonts/medeo/$1")')
}

async function main() {
  if (!existsSync(pkgDist)) {
    throw new Error('medeo-font is not installed: npm install medeo-font@1.0.0')
  }

  await mkdir(outCssDir, { recursive: true })
  await mkdir(outFontsDir, { recursive: true })

  const chunks = [
    '/* GENERATED by scripts/sync-fonts.mjs — do not edit manually.\n' +
      '   Font: medeo-font@1.0.0 (SIL OFL 1.1), self-hosted, no CDN. */\n',
  ]
  const copied = []

  for (const style of STYLES) {
    const src = join(pkgDist, `${style}.css`)
    const css = dropItalic(rewriteUrls(await readFile(src, 'utf8')))
    chunks.push(`\n/* ${style} */\n${css}`)

    const dir = join(pkgDist, 'fonts', `medeo-${style}`)
    for (const file of await readdir(dir)) {
      if (!file.endsWith('.woff2')) continue
      if (file.includes('Italic')) continue // the UI has no italic styles
      await copyFile(join(dir, file), join(outFontsDir, `medeo-${style}`, file)).catch(async () => {
        await mkdir(join(outFontsDir, `medeo-${style}`), { recursive: true })
        await copyFile(join(dir, file), join(outFontsDir, `medeo-${style}`, file))
      })
      copied.push(`medeo-${style}/${file}`)
    }
  }

  await writeFile(join(outCssDir, 'fonts.generated.css'), chunks.join(''), 'utf8')
  console.log(`fonts.generated.css: ${STYLES.join(', ')}; files copied: ${copied.length}`)
  console.log('preload files:', copied.filter((f) => /\.(latin|cyrillic)\.woff2$/.test(f)).join(', '))
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
